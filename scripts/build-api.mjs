// Bundles src/server/aiBriefHandler.ts (and the src/lib modules and data/*.json it imports) into one
// self-contained ES module, api/_lib/ai-brief-core.js, which the Vercel Function api/ai-brief.ts
// imports. Generated at build time by `npm run build` (Vercel runs it too) and gitignored: never commit
// or hand-edit it. `npm run build:api` regenerates it for local checks.
// Files under api/_lib are not deployed as functions (underscore prefix).
import { build } from 'vite';

await build({
  configFile: false,
  logLevel: 'warn',
  publicDir: false,
  ssr: { noExternal: true },
  build: {
    ssr: 'src/server/aiBriefHandler.ts',
    outDir: 'api/_lib',
    emptyOutDir: false,
    copyPublicDir: false,
    minify: false,
    sourcemap: false,
    target: 'node22',
    rolldownOptions: {
      output: {
        format: 'es',
        entryFileNames: 'ai-brief-core.js',
        banner: '// GENERATED by scripts/build-api.mjs from src/server/aiBriefHandler.ts. Do not edit.\n/* eslint-disable */',
      },
    },
  },
});
console.log('build:api: wrote api/_lib/ai-brief-core.js');

